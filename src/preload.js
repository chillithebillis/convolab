const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('native', {
  platform: process.platform,
  pathFor: file => { try{ return webUtils.getPathForFile(file) || null; }catch(e){ return null; } },
  saveDialog: o => ipcRenderer.invoke('saveDialog', o),
  writeFile: (p, data) => ipcRenderer.invoke('writeFile', p, data),
  readFile: p => ipcRenderer.invoke('readFile', p),
  reveal: p => ipcRenderer.invoke('reveal', p),
  displays: () => ipcRenderer.invoke('displays'),
  setOutputDisplay: id => ipcRenderer.invoke('setOutputDisplay', id),
  presetsList: () => ipcRenderer.invoke('presetsList'),
  presetSave: (n, j, t) => ipcRenderer.invoke('presetSave', n, j, t),
  presetDelete: n => ipcRenderer.invoke('presetDelete', n),
  makeProxy: p => ipcRenderer.invoke('makeProxy', p),
  convertImage: p => ipcRenderer.invoke('convertImage', p),
  extractAudio: p => ipcRenderer.invoke('extractAudio', p),
  encStart: o => ipcRenderer.invoke('encStart', o),
  encFrame: (id, buf) => ipcRenderer.invoke('encFrame', id, buf),
  encFinish: id => ipcRenderer.invoke('encFinish', id),
  encCancel: id => ipcRenderer.invoke('encCancel', id),
  onMenu: cb => ipcRenderer.on('menu', (_e, cmd) => cb(cmd)),
  askMedia: kind => ipcRenderer.invoke('askMedia', kind),
  version: () => ipcRenderer.invoke('version'),
  checkUpdates: () => ipcRenderer.invoke('checkUpdates'),
  installUpdate: () => ipcRenderer.invoke('installUpdate'),
  onUpdate: cb => ipcRenderer.on('update', (_e, o) => cb(o)),
});
